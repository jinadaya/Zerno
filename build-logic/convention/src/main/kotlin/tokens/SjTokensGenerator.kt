package tokens

import groovy.json.JsonSlurper
import java.util.Locale
import kotlin.math.roundToInt

/**
 * Turns the design system's `tokens.json` into Kotlin source for `:designsystem`.
 * Pure function of its input so the Gradle task stays a thin wrapper.
 */
internal object SjTokensGenerator {

    /** Spacing names the components use instead of a raw step, mapped to the step they stand for. */
    val spacingAliases: Map<String, String> = linkedMapOf(
        "gutter" to "space-4",
        "sticker-padding" to "space-6",
    )

    /** Returns file name to file content. */
    fun generate(json: String, packageName: String, sourceName: String): Map<String, String> {
        @Suppress("UNCHECKED_CAST")
        val root = JsonSlurper().parseText(json) as Map<String, Any?>
        val header = "// Generated by generateSjTokens from $sourceName. Do not edit; change the json instead.\n" +
            "package $packageName\n"
        return mapOf(
            "SjColors.kt" to header + colors(root),
            "SjSpacing.kt" to header + spacing(root),
            "SjRadius.kt" to header + radius(root),
            "SjSize.kt" to header + size(root),
        )
    }

    private fun colors(root: Map<String, Any?>): String {
        val color = root.obj("color")
        val themes = color.list("themes").map { (it as Map<*, *>)["id"].toString() }
        require("light" in themes && "dark" in themes) { "tokens.json: color.themes must include light and dark, got $themes" }
        val tokens = color.list("tokens").map { it as Map<*, *> }

        val props = tokens.joinToString("\n") { token ->
            "    /** ${token.usage()} */\n    val ${token.name().camel()}: Color,"
        }
        fun instance(theme: String) = tokens.joinToString("\n") { token ->
            val values = token["value"] as? Map<*, *> ?: error("tokens.json: color ${token.name()} has no themed value")
            val raw = values[theme]?.toString() ?: error("tokens.json: color ${token.name()} has no $theme value")
            "        ${token.name().camel()} = ${colorLiteral(token.name(), raw)},"
        }

        return """
            |
            |import androidx.compose.runtime.Immutable
            |import androidx.compose.ui.graphics.Color
            |
            |/** Colour tokens. Use [Light] or [Dark]; both come from the same token list. */
            |@Immutable
            |data class SjColors(
            |$props
            |) {
            |    companion object {
            |        val Light: SjColors = SjColors(
            |${instance("light")}
            |        )
            |
            |        val Dark: SjColors = SjColors(
            |${instance("dark")}
            |        )
            |    }
            |}
            |""".trimMargin()
    }

    private fun spacing(root: Map<String, Any?>): String {
        val tokens = root.obj("spacing").list("tokens").map { it as Map<*, *> }
        val byName = tokens.associateBy { it.name() }
        val props = tokens.map { token ->
            Prop(token.name().camel(), token.usage(), "Dp", dimension(token.name(), token["value"].toString()))
        }
        val aliases = spacingAliases.map { (alias, target) ->
            val token = byName[target] ?: error("tokens.json: spacing alias $alias points at missing $target")
            Prop(alias.camel(), "Same as ${target.camel()}: ${token.usage()}", "Dp", dimension(target, token["value"].toString()))
        }
        return tokenClass("SjSpacing", "Spacing scale, plus named aliases for the common gaps.", props + aliases, "dp")
    }

    private fun radius(root: Map<String, Any?>): String {
        val props = root.obj("radius").list("tokens").map { it as Map<*, *> }.map { token ->
            Prop(token.name().removePrefix("radius-").camel(), token.usage(), "Dp", dimension(token.name(), token["value"].toString()))
        }
        return tokenClass("SjRadius", "Corner radii.", props, "dp")
    }

    private fun size(root: Map<String, Any?>): String {
        val props = root.obj("size").list("tokens").map { it as Map<*, *> }.map { token ->
            val value = token["value"].toString()
            val type = if (value.endsWith("em")) "TextUnit" else "Dp"
            Prop(token.name().camel(), token.usage(), type, dimension(token.name(), value))
        }
        val units = if (props.any { it.type == "TextUnit" }) "dp_em" else "dp"
        return tokenClass("SjSize", "Fixed component sizes. `em` sizes are relative to the text they measure.", props, units)
    }

    private data class Prop(val name: String, val doc: String, val type: String, val value: String)

    private fun tokenClass(name: String, doc: String, props: List<Prop>, units: String): String {
        val imports = buildList {
            add("androidx.compose.runtime.Immutable")
            add("androidx.compose.ui.unit.Dp")
            add("androidx.compose.ui.unit.dp")
            if (units == "dp_em") {
                add("androidx.compose.ui.unit.TextUnit")
                add("androidx.compose.ui.unit.em")
            }
        }.joinToString("\n") { "import $it" }
        val body = props.joinToString("\n") { "    /** ${it.doc} */\n    val ${it.name}: ${it.type} = ${it.value}," }
        return """
            |
            |$imports
            |
            |/** $doc */
            |@Immutable
            |data class $name(
            |$body
            |) {
            |    companion object {
            |        val Default: $name = $name()
            |    }
            |}
            |""".trimMargin()
    }

    private val hex = Regex("^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
    private val rgba = Regex("""^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([0-9.]+)\s*)?\)$""")

    /** `#RRGGBB`, `#RRGGBBAA` or `rgba(r,g,b,a)` to a `Color(0xAARRGGBB)` literal. */
    internal fun colorLiteral(token: String, raw: String): String {
        val value = raw.trim()
        val argb = hex.matchEntire(value)?.let {
            val digits = it.groupValues[1].uppercase(Locale.ROOT)
            if (digits.length == 6) "FF$digits" else digits.substring(6) + digits.substring(0, 6)
        } ?: rgba.matchEntire(value)?.let {
            val (r, g, b) = it.groupValues.drop(1).take(3).map { c -> c.toInt() }
            require(listOf(r, g, b).all { c -> c in 0..255 }) { "tokens.json: color $token is out of range: $raw" }
            val a = it.groupValues[4].ifEmpty { "1" }.toDouble()
            require(a in 0.0..1.0) { "tokens.json: color $token alpha is out of range: $raw" }
            listOf((a * 255).roundToInt(), r, g, b).joinToString("") { c -> "%02X".format(c) }
        } ?: error("tokens.json: color $token is not #RRGGBB, #RRGGBBAA or rgba(): $raw")
        return "Color(0x$argb)"
    }

    private val unit = Regex("""^(-?\d+(?:\.\d+)?)(px|em)$""")

    /** `16px` to `16.dp` (one CSS px is one dp), `32em` to `32.em`. */
    internal fun dimension(token: String, raw: String): String {
        val match = unit.matchEntire(raw.trim()) ?: error("tokens.json: $token is not a px or em value: $raw")
        val (number, suffix) = match.destructured
        val kotlinNumber = if ('.' in number) "${number}f" else number
        return if (suffix == "px") "$kotlinNumber.dp" else "$kotlinNumber.em"
    }

    /** `reader-paper` to `readerPaper`, `space-1` to `space1`. */
    internal fun String.camel(): String =
        split('-').filter { it.isNotEmpty() }.mapIndexed { i, part ->
            if (i == 0) part else part.replaceFirstChar { it.titlecase(Locale.ROOT) }
        }.joinToString("")

    private fun Map<*, *>.name(): String = this["name"]?.toString() ?: error("tokens.json: token without a name: $this")

    private fun Map<*, *>.usage(): String = (this["usage"]?.toString() ?: "").replace("*/", "* /")

    @Suppress("UNCHECKED_CAST")
    private fun Map<String, Any?>.obj(key: String): Map<String, Any?> =
        this[key] as? Map<String, Any?> ?: error("tokens.json: missing object \"$key\"")

    private fun Map<String, Any?>.list(key: String): List<Any?> =
        this[key] as? List<Any?> ?: error("tokens.json: missing list \"$key\"")
}
