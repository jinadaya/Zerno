#!/usr/bin/env python3
"""Writes SjIcons.kt from Lucide SVGs.

Usage: npm pack lucide-static@0.460.0 && tar xzf lucide-static-*.tgz
       python3 designsystem/icons/import_lucide.py package/icons

Only the icons in ICONS are imported. Add a line there and run the script again; do not edit SjIcons.kt by hand.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

LUCIDE_VERSION = "0.460.0"

# Kotlin name -> Lucide file name, and what the screens use it for.
ICONS = [
    ("Today", "sun", "Today tab"),
    ("Bible", "book-open", "Bible tab"),
    ("Plans", "list", "Plans tab"),
    ("Journey", "chart-no-axes-column", "Journey tab"),
    ("Highlight", "highlighter", "Verse action: highlight"),
    ("Save", "bookmark", "Verse action: save"),
    ("Reflect", "notebook-pen", "Verse action: reflect, Lumi's notes"),
    ("Share", "share", "Verse action: share"),
    ("Copy", "copy", "Verse action: copy"),
    ("ArrowRight", "arrow-right", "Primary button arrow, next"),
    ("ArrowLeft", "arrow-left", "Previous"),
    ("ChevronLeft", "chevron-left", "Back"),
    ("ChevronRight", "chevron-right", "Row disclosure"),
    ("ChevronDown", "chevron-down", "Expand, book picker"),
    ("Close", "x", "Close a sheet"),
    ("Check", "check", "Done, finished plan"),
    ("Lock", "lock", "Locked achievement"),
    ("Settings", "settings", "Settings"),
    ("Reminder", "bell", "Reminders"),
    ("Streak", "flame", "Streak"),
    ("TextSize", "a-large-small", "Reader text size"),
    ("Translation", "languages", "Translation switcher"),
    ("Search", "search", "Search"),
    ("Add", "plus", "Add"),
]

NS = "{http://www.w3.org/2000/svg}"


def num(v):
    f = float(v)
    return str(int(f)) if f == int(f) else repr(f)


def element_path(el):
    tag = el.tag.replace(NS, "")
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = (float(a[k]) for k in ("cx", "cy", "r"))
        return f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0Z"
    if tag == "ellipse":
        cx, cy, rx, ry = (float(a[k]) for k in ("cx", "cy", "rx", "ry"))
        return f"M{num(cx - rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0Z"
    if tag == "line":
        return f"M{num(a['x1'])} {num(a['y1'])}L{num(a['x2'])} {num(a['y2'])}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{num(pts[i])} {num(pts[i + 1])}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        if rx == 0:
            return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
        return (
            f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(ry)}"
            f"v{num(h - 2 * ry)}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(ry)}"
            f"h{num(-(w - 2 * rx))}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(-ry)}"
            f"v{num(-(h - 2 * ry))}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(-ry)}Z"
        )
    raise ValueError(f"unsupported element {tag}")


def icon_paths(svg_file):
    root = ET.parse(svg_file).getroot()
    assert root.attrib.get("viewBox") == "0 0 24 24", svg_file
    return [element_path(el) for el in root.iter() if el is not root and el.tag.replace(NS, "") != "g"]


def main(icons_dir, out_file):
    entries = []
    for name, file, usage in ICONS:
        paths = icon_paths(os.path.join(icons_dir, f"{file}.svg"))
        args = "".join(f'\n            "{p}",' for p in paths)
        entries.append(
            f"    /** {usage}. Lucide `{file}`. */\n"
            f'    val {name}: ImageVector by lazy {{\n        lucide(\n            "{name}",{args}\n        )\n    }}\n'
        )
    body = "\n".join(entries)
    out = f"""// Generated by designsystem/icons/import_lucide.py from lucide-static {LUCIDE_VERSION}. Do not edit; add the
// icon to the script and run it again. Lucide is ISC licensed: designsystem/icons/LICENSE-lucide.txt.
package app.zerno.designsystem.icon

import androidx.compose.ui.graphics.vector.ImageVector

/**
 * The line icons the screens use, from Lucide: 24 dp, 2 dp stroke, round caps and joins. Draw them with [SjIcon],
 * which tints them with the content colour. Icons back up words; tabs and actions always keep their labels.
 */
object SjIcons {{
{body}}}
"""
    with open(out_file, "w") as f:
        f.write(out)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "..", "src", "commonMain", "kotlin", "app", "zerno", "designsystem", "icon", "SjIcons.kt")
    main(sys.argv[1], os.path.normpath(target))
